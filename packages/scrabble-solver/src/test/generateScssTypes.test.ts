import { afterEach, beforeEach, describe, expect, it, mock, spyOn } from 'bun:test';
import * as realFs from 'node:fs';

type WatchListener = (event: string, filename: string | null) => void;

const compiled = new Map<string, string>();
const files = new Map<string, string>();
const logs: string[] = [];
let watchListener: WatchListener | undefined;

await mock.module('sass', () => ({
  initCompiler: () => ({
    compile: (file: string) => ({ css: readCompiled(file) }),
    dispose: () => {
      logs.push('disposed');
    },
  }),
}));
await mock.module('node:fs', () => ({
  ...realFs,
  existsSync: (path: string) => files.has(path),
  readdirSync: () => [...compiled.keys()],
  readFileSync: (path: string) => files.get(path),
  unlinkSync: (path: string) => files.delete(path),
  watch: (_directory: string, _options: object, listener: WatchListener) => {
    watchListener = listener;
  },
  writeFileSync: (path: string, content: string) => files.set(path, content),
}));

const originalArgv = process.argv;
let logSpy: ReturnType<typeof spyOn>;
let runId = 0;

beforeEach(() => {
  compiled.clear();
  files.clear();
  logs.length = 0;
  watchListener = undefined;
  logSpy = spyOn(console, 'log').mockImplementation((message: string) => {
    logs.push(message);
  });
});

afterEach(() => {
  logSpy.mockRestore();
  process.argv = originalArgv;
});

describe('generate-scss-types', () => {
  it('writes a sibling type file for every module stylesheet, skipping others', async () => {
    compiled.set('b.module.scss', '.b {}');
    compiled.set('a.module.scss', '.a {}');
    compiled.set('plain.scss', '.plain {}');

    await run();

    expect([...files.keys()].map(readFilename)).toEqual(['a.module.scss.d.ts', 'b.module.scss.d.ts']);
    expect(logs).toContain('Generated type definitions for 2 .module.scss files');
  });

  it('lists sorted, unique class names', async () => {
    compiled.set('a.module.scss', '.zebra .apple {} .apple {}');

    await run();

    expect(readTypes()).toEqual(['apple', 'zebra']);
  });

  it('includes keyframes and :export keys, the other names a module exposes', async () => {
    compiled.set('a.module.scss', '@keyframes spin { from { top: 0 } } :export { colorBlue: #000; }');

    await run();

    expect(readTypes()).toEqual(['colorBlue', 'spin']);
  });

  it('excludes :global classes', async () => {
    compiled.set('a.module.scss', ':global(.external) .local {}');

    await run();

    expect(readTypes()).toEqual(['local']);
  });

  it('quotes names that are not identifiers', async () => {
    compiled.set('a.module.scss', '.with-dash {}');

    await run();

    expect(readFile()).toContain("readonly 'with-dash': string;");
  });

  it('writes a complete declaration', async () => {
    compiled.set('a.module.scss', '.a {}');

    await run();

    expect(readFile()).toBe(
      [
        '// Generated by scripts/generate-scss-types.ts - do not edit.',
        'declare const styles: {',
        '  readonly a: string;',
        '};',
        '',
        'export default styles;',
        '',
      ].join('\n'),
    );
  });

  it('does not touch an up-to-date file', async () => {
    compiled.set('a.module.scss', '.a {}');
    await run();
    logs.length = 0;

    await run();

    expect(logs.filter((log) => log.startsWith('Generated src'))).toEqual([]);
  });

  it('releases the compiler when not watching', async () => {
    await run();

    expect(logs).toContain('disposed');
  });

  describe('--watch', () => {
    beforeEach(() => {
      process.argv = [...originalArgv, '--watch'];
    });

    it('keeps the compiler alive', async () => {
      await run();

      expect(logs).not.toContain('disposed');
      expect(watchListener).toBeDefined();
    });

    it('regenerates a changed stylesheet', async () => {
      await run();
      compiled.set('a.module.scss', '.fresh {}');
      files.set(findStylesheet(), '');

      watchListener?.('change', 'a.module.scss');

      expect(files.get(`${findStylesheet()}.d.ts`)).toContain('fresh');
    });

    it('removes the types of a deleted stylesheet', async () => {
      await run();
      files.set(`${findStylesheet()}.d.ts`, 'stale');

      watchListener?.('rename', 'a.module.scss');

      expect(files.has(`${findStylesheet()}.d.ts`)).toBe(false);
    });

    it('ignores a deleted stylesheet with no types', async () => {
      await run();

      expect(() => {
        watchListener?.('rename', 'a.module.scss');
      }).not.toThrow();
    });

    it('ignores other files', async () => {
      await run();
      watchListener?.('change', 'a.tsx');
      watchListener?.('change', null);

      expect(files.size).toBe(0);
    });

    it('logs compile errors instead of stopping the watcher', async () => {
      const errors: string[] = [];
      const errorSpy = spyOn(console, 'error').mockImplementation((message: string) => {
        errors.push(message);
      });

      await run();
      files.set(findStylesheet(), '');
      compiled.set('a.module.scss', 'THROW');

      watchListener?.('change', 'a.module.scss');
      errorSpy.mockRestore();

      expect(errors).toEqual(['Error: Undefined variable']);
    });
  });
});

function readCompiled(file: string): string {
  const css = compiled.get(readFilename(file)) ?? '';

  if (css === 'THROW') {
    throw new Error('Undefined variable');
  }

  return css;
}

function run(): Promise<unknown> {
  return import(`../../scripts/generate-scss-types.ts?run=${++runId}`);
}

function readFilename(path: string): string {
  return path.split('/').at(-1)!;
}

function findStylesheet(): string {
  return `${import.meta.dir.replace('/src/test', '')}/src/a.module.scss`;
}

function readFile(): string {
  return [...files.values()][0];
}

function readTypes(): string[] {
  return Array.from(readFile().matchAll(/readonly '?([\w-]+)'?:/g), ([, name]) => name);
}
